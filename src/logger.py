class Logger:
    def __init__(self):

        db_uri = get_db_uri()
        self.engine = create_engine(db_uri)
        Base.metadata.create_all(self.engine)
        self.session_factory = sessionmaker(bind=self.engine, expire_on_commit=True)
        self.Session = scoped_session(self.session_factory)

        self.inspector = inspect(self.engine)
        if STUDENT_RESPONSE_TABLE not in self.inspector.get_table_names():
            Base.metadata.tables[STUDENT_RESPONSE_TABLE].create(self.engine)

        if GENERATED_EXERCISE_TABLE not in self.inspector.get_table_names():
            Base.metadata.tables[GENERATED_EXERCISE_TABLE].create(self.engine)

        if SENTENCE_PAIR_RATING_TABLE not in self.inspector.get_table_names():
            Base.metadata.tables[SENTENCE_PAIR_RATING_TABLE].create(self.engine)

        self._ensure_student_response_schema()

    def _ensure_student_response_schema(self):
        """Add newly introduced columns to student_responses if they are missing.

        create_all only creates missing tables; on an existing deployment the
        table predates these columns, so they have to be added explicitly.
        """
        existing_columns = {col['name'] for col in self.inspector.get_columns(STUDENT_RESPONSE_TABLE)}

        with self.engine.begin() as connection:
            if 'translation_mode' not in existing_columns:
                connection.execute(
                    text(f"ALTER TABLE {STUDENT_RESPONSE_TABLE} ADD COLUMN translation_mode VARCHAR DEFAULT ''")
                )

    def record(self, log):
        with self.Session() as session:
            print("Recording log")
            session.add(log)
            session.commit()

    def getRatedEnglishFormulas(self, user_id):
        """Return a set of LTL formulas this user has already rated."""
        if not isinstance(user_id, str):
            raise ValueError("user_id should be a string")

        with self.Session() as session:
            rows = session.query(EnglishLTLRating.ltl).filter(
                EnglishLTLRating.user_id == user_id
            ).all()
            return {row.ltl for row in rows if row.ltl}

    
    @staticmethod
    def _parse_misconceptions(value):
        """Normalize misconception metadata from HTML dataset or JSON values."""
        if value is None:
            return []
        if isinstance(value, (list, tuple)):
            return [str(code) for code in value]
        if not isinstance(value, str):
            return []
        try:
            parsed = ast.literal_eval(value)
        except (ValueError, SyntaxError):
            try:
                parsed = json.loads(value)
            except (TypeError, ValueError):
                return []
        return [str(code) for code in parsed] if isinstance(parsed, (list, tuple)) else []

    @staticmethod
    def _is_modeled_code(code):
        from codebook import MisconceptionCode
        parsed = MisconceptionCode.from_string(code)
        return parsed is not None and parsed != MisconceptionCode.Syntactic

    def _build_opportunity_events(self, attempt, options, _selected_codes):
        """Build v1 option-aware observations without treating ambiguity as mastery."""
        from misconceptionmodel import MODEL_VERSION

        occurrences = {}
        selected_option_codes = []
        for option in options:
            codes = [
                code for code in self._parse_misconceptions(option.get('misconceptions'))
                if self._is_modeled_code(code)
            ]
            if str(option.get('value', '')) == str(attempt.selected_option):
                selected_option_codes = codes
            if not codes:
                continue
            probe_type = "merged" if len(codes) > 1 else "direct"
            for code in codes:
                occurrences.setdefault(code, []).append((codes, probe_type))

        option_count = max(1, len(options))
        events = []
        for code, probes in occurrences.items():
            if code in selected_option_codes:
                # Positive strength comes from the option actually selected,
                # even if a more direct option for this code was also shown.
                codes = selected_option_codes
                probe_type = "merged" if len(codes) > 1 else "direct"
                observation = "positive"
                strength = 1.0 / len(codes)
            else:
                # Duplicate representations are one opportunity. For negative
                # evidence, use the most direct displayed probe.
                codes, probe_type = min(probes, key=lambda probe: len(probe[0]))
                if attempt.correct_answer:
                    observation = "negative"
                    strength = (1.0 - (1.0 / option_count)) / len(codes)
                else:
                    observation = "ambiguous"
                    strength = 0.0

            events.append(MisconceptionOpportunity(
                attempt_id=attempt.id,
                user_id=attempt.user_id,
                timestamp=attempt.timestamp,
                misconception=code,
                observation=observation,
                evidence_strength=strength,
                probe_type=probe_type,
                policy_version=MODEL_VERSION,
            ))
        return events

    def logStudentResponse(self, userId, misconceptions, question_text, question_options, correct_answer, questiontype, mp_class, exercise, course, translation_mode="", selected_option="", correct_option="", attempt_id=None):

        if not isinstance(userId, str):
            raise ValueError("userId should be a string")
        if not isinstance(question_text, str):
            raise ValueError("question_text should be a string")
        if not isinstance(question_options, str):
            raise ValueError("question_options should be a string")
        if not isinstance(correct_answer, bool):
            raise ValueError("correct_answer should be a boolean")
        if not isinstance(questiontype, str):
            raise ValueError("questiontype should be a string")
        if not isinstance(mp_class, str):
            raise ValueError("mp_class should be a string")
        if not isinstance(exercise, str):
            raise ValueError("exercise should be a string")
        
        if not isinstance(course, str):
            raise ValueError("course should be a string")

        timestamp = datetime.datetime.now()
        legacy_logs = []
        if misconceptions is None or len(misconceptions) == 0:
            legacy_logs.append(StudentResponse(user_id=userId, timestamp=timestamp,
                                               misconception="", question_text=question_text, question_options=question_options, correct_answer=correct_answer,
                                               question_type=questiontype, mp_class=mp_class, exercise=exercise, course=course, translation_mode=translation_mode))

        for misconception in misconceptions or []:
            if not isinstance(misconception, str):
                raise ValueError("misconception should be a string")
            legacy_logs.append(StudentResponse(user_id=userId, timestamp=timestamp,
                                               misconception=misconception, question_text=question_text, question_options=question_options, correct_answer=correct_answer,
                                               question_type=questiontype, mp_class=mp_class, exercise=exercise, course=course, translation_mode=translation_mode))

        try:
            options = json.loads(question_options)
            if not isinstance(options, list):
                options = []
        except (TypeError, ValueError):
            options = []

        from misconceptionmodel import MODEL_VERSION
        question_fingerprint = json.dumps(
            {"type": questiontype, "text": question_text, "options": options},
            sort_keys=True,
            separators=(",", ":"),
        )
        stable_attempt_id = (
            hashlib.sha256(f"{userId}\0{attempt_id}".encode("utf-8")).hexdigest()
            if attempt_id else str(uuid.uuid4())
        )
        attempt = MisconceptionAttempt(
            id=stable_attempt_id,
            user_id=userId,
            timestamp=timestamp,
            question_id=hashlib.sha256(question_fingerprint.encode("utf-8")).hexdigest(),
            question_type=questiontype,
            correct_answer=correct_answer,
            selected_option=selected_option,
            correct_option=correct_option,
            option_count=len(options),
            exercise=exercise,
            course=course,
            policy_version=MODEL_VERSION,
            question_options=question_options,
        )
        opportunities = self._build_opportunity_events(attempt, options, misconceptions or [])

        # One transaction prevents a partial attempt from disagreeing with its
        # opportunities or with the legacy classroom reports.
        with self.Session() as session:
            if session.get(MisconceptionAttempt, attempt.id) is not None:
                return
            session.add(attempt)
            session.add_all(opportunities)
            session.add_all(legacy_logs)
            try:
                session.commit()
            except IntegrityError:
                session.rollback()
                # A concurrent retry may win after both requests passed the
                # check above. Treat only that duplicate-attempt race as an
                # idempotent success; re-raise unrelated integrity failures.
                if session.get(MisconceptionAttempt, attempt.id) is None:
                    raise

    
    def getUserLogs(self, userId, lookback_days=30):
        if not isinstance(userId, str):
            raise ValueError("userId should be a string")

        with self.Session() as session:
            lookback_date = datetime.datetime.now() - datetime.timedelta(days=lookback_days)
            logs = session.query(StudentResponse).filter(StudentResponse.user_id == userId, StudentResponse.timestamp >= lookback_date).all()
            return logs

    def getUserMisconceptionOpportunities(self, userId, lookback_days=30):
        """Return versioned option-aware misconception evidence for a learner."""
        if not isinstance(userId, str):
            raise ValueError("userId should be a string")

        from misconceptionmodel import MODEL_VERSION
        with self.Session() as session:
            lookback_date = datetime.datetime.now() - datetime.timedelta(days=lookback_days)
            return session.query(MisconceptionOpportunity).filter(
                MisconceptionOpportunity.user_id == userId,
                MisconceptionOpportunity.timestamp >= lookback_date,
                MisconceptionOpportunity.policy_version == MODEL_VERSION,
            ).order_by(MisconceptionOpportunity.timestamp).all()


    def recordGeneratedExercise(self, userId, exercise_data, exercise_name, complexity=None):
        if not isinstance(userId, str):
            raise ValueError("userId should be a string")
        if not isinstance(exercise_data, str):
            raise ValueError("exercise_data should be a string")
        if complexity is not None and not isinstance(complexity, int):
            raise ValueError("complexity should be an int or None")
        
        log = GeneratedExercise(user_id=userId, timestamp=datetime.datetime.now(), exercise_data=exercise_data, exerciseName=exercise_name, complexity=complexity)
        self.record(log)



    def recordEnglishLTLPair(self, e_l_pair):

        if not isinstance(e_l_pair, dict):
            raise ValueError("e_l_pair should be a dictionary")
        
        if 'english' not in e_l_pair or 'ltl' not in e_l_pair:
            raise ValueError("e_l_pair should contain 'english' and 'ltl' keys")
        
        english = e_l_pair['english']
        ltl = e_l_pair['ltl']
        comments = e_l_pair['comments']
        userId = e_l_pair['user_id']


        log = EnglishLTLRating(english=english, ltl=ltl, comments=comments, user_id=userId)
        self.record(log)

    def logSentencePairRating(self, rating_data):
        """Insert or update a user's rating for a specific benchmark row."""
        required = ['user_id', 'dataset', 'row_index']
        for key in required:
            if key not in rating_data:
                raise ValueError(f"rating_data missing required key '{key}'")

        unsure = bool(rating_data.get('unsure'))
        likert = rating_data.get('likert_rating')
        if not unsure:
            if not isinstance(likert, int) or likert < 1 or likert > 7:
                raise ValueError("likert_rating must be an int between 1 and 7 for 7-point scale")
        else:
            likert = None

        with self.Session() as session:
            existing = session.query(SentencePairRating).filter(
                SentencePairRating.user_id == rating_data['user_id'],
                SentencePairRating.dataset == rating_data['dataset'],
                SentencePairRating.row_index == rating_data['row_index']
            ).one_or_none()

            if existing:
                existing.likert_rating = likert
                existing.notes = rating_data.get('notes', '')
                existing.unsure = unsure
                existing.base_english = rating_data.get('base_english', existing.base_english)
                existing.mutant_english = rating_data.get('mutant_english', existing.mutant_english)
                existing.base_ltl = rating_data.get('base_ltl', existing.base_ltl)
                existing.mutant_ltl = rating_data.get('mutant_ltl', existing.mutant_ltl)
                existing.misconception = rating_data.get('misconception', existing.misconception)
                existing.closest_distance = rating_data.get('closest_distance', existing.closest_distance)
                existing.max_distance = rating_data.get('max_distance', existing.max_distance)
                existing.avg_distance = rating_data.get('avg_distance', existing.avg_distance)
                existing.num_mutants = rating_data.get('num_mutants', existing.num_mutants)
            else:
                log = SentencePairRating(
                    user_id=rating_data['user_id'],
                    dataset=rating_data['dataset'],
                    row_index=rating_data['row_index'],
                    base_english=rating_data.get('base_english', ''),
                    mutant_english=rating_data.get('mutant_english', ''),
                    base_ltl=rating_data.get('base_ltl', ''),
                    mutant_ltl=rating_data.get('mutant_ltl', ''),
                    misconception=rating_data.get('misconception', ''),
                    likert_rating=likert,
                    notes=rating_data.get('notes', ''),
                    unsure=unsure,
                    closest_distance=rating_data.get('closest_distance'),
                    max_distance=rating_data.get('max_distance'),
                    avg_distance=rating_data.get('avg_distance'),
                    num_mutants=rating_data.get('num_mutants')
                )
                session.add(log)

            session.commit()

    def getRatedSentencePairIndices(self, user_id, dataset):
        """Return a set of row indices already rated by the user for the dataset."""
        if not isinstance(user_id, str):
            raise ValueError("user_id should be a string")
        if not isinstance(dataset, str):
            raise ValueError("dataset should be a string")

        with self.Session() as session:
            rows = session.query(SentencePairRating.row_index).filter(
                SentencePairRating.user_id == user_id,
                SentencePairRating.dataset == dataset
            ).all()
            return {row[0] for row in rows}


    def getComplexity(self, userId):
        if not isinstance(userId, str):
            raise ValueError("userId should be a string")

        with self.Session() as session:
            complexity = session.query(GeneratedExercise.complexity).filter(GeneratedExercise.user_id == userId).order_by(GeneratedExercise.timestamp.desc()).first()
            return complexity[0] if complexity else None
    

